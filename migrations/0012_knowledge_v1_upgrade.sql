## 训练阶段发生了什么

训练不是把知识“装进”模型。实际发生的是一件更朴素的事：

模型拿到一段文本，被要求预测被遮住或下一个位置的词，然后把自己的预测和正确答案比较，根据差距调整内部参数。这个过程在数十亿条文本上重复数万亿次。

举一个简化例子。模型看到：

> 今天天气真____

如果训练语料里大量出现“今天天气真好”，模型学会让“好”这个位置获得最高概率。单个例子微不足道，但当训练数据覆盖了网页、书籍、代码、论文、论坛，模型学到的是**语言的结构性规律**：

- “苹果”和“水果”经常出现在相似语境里；
- “如果……那么……”后面通常跟着结论；
- 一段产品需求文档通常包含背景、目标、方案、验收标准；
- 代码里 `for` 循环之后通常是循环体。

这些规律以数千亿个浮点参数的形式存储。注意关键词：**规律**，不是**事实**。模型没有“记住”维基百科词条，它记住的是词与词之间统计上的共现关系。这也解释了它为什么能把知识以新组合的方式输出——组合规律是它的本职。

## 推理阶段发生了什么

推理就是“续写”。你输入问题，模型把问题切成Token（可以理解为词或字的片段），然后循环执行：

1. 根据当前所有内容，计算下一个Token的概率分布；
2. 按概率采样出一个Token；
3. 把这个Token追加到内容里，重复。

你看到的回答，是模型一次一次“猜下一个词”猜出来的。每次生成的Token都会成为下一次预测的输入，所以**前面的错误会积累**，这也正是长任务容易跑偏的原因之一。

> 关键区分：训练阶段改参数（只有厂商能做，成本极高）；推理阶段用参数（每次提问都在发生，按Token计费）。

## 一个具体的例子

假设你在写一封邮件，写了开头：

> 尊敬的张经理，感谢您上周安排的产品评审会。关于数据看板的上线时间，我们内部讨论后认为……

模型到这里开始预测下一个Token。它的概率分布可能是：

| 候选内容 | 模型估计的概率 | 你会看到的结果 |
| --- | --- | --- |
| “可以提前到” | 较高 | 顺着承诺提前 |
| “需要推迟到” | 较高 | 顺着申请延期 |
| “没有问题” | 中等 | 直接确认 |

模型选哪个，取决于训练数据里类似语境的统计倾向、你之前的全部文字，以及采样参数（temperature）。**同一个开头，模型可能给出方向相反的续写**——这就是为什么模型输出有随机性，也是为什么重要决策不能只靠一次回答。

## 为什么“预测下一个词”能产生复杂能力

这是最反直觉的地方：一个只学“猜词”的系统，为什么能翻译、写代码、做数学题？

答案是：**这些能力都隐含在语言本身里**。数学证明是用语言写的，代码是用语言写的，推理过程也是用语言表达的。当模型学会“给定大量上下文，下一步最可能出现什么”，它其实在训练数据覆盖的范围内，学会了大量任务的过程性规律：

- 翻译：中英对照语料里，“你好”后面跟着“Hello”的概率极高；
- 写代码：错误信息后面通常跟着修复建议；
- 推理：题目后面通常跟着逐步解答。

研究上有一个著名的观察：让模型把思考过程**写出来**再给结论（Chain-of-Thought），复杂题目的正确率会显著提升，因为“把推理过程语言化”恰好命中了模型擅长的模式。这不是魔法，而是模型在训练语料里见过太多“先分析后结论”的文本。

## 模型记忆和知识库有什么区别

这是最容易混淆的一点：

| 维度 | 模型参数里的“记忆” | 外部知识库 |
| --- | --- | --- |
| 存储形式 | 统计规律（参数） | 明确的文本/记录 |
| 更新方式 | 需要重新训练/微调 | 随时增删改 |
| 可追溯性 | 无法定位“哪段训练数据” | 每条都有来源 |
| 错误表现 | 自信地给出似是而非的答案 | 有或没有，可检查 |

模型参数里的知识有三个固有缺陷：**截止时间**（训练数据只到某个时间点）、**权重稀释**（冷门事实被平均掉）、**无法校验**（你不知道它依据什么）。所以严肃产品的做法是：模型负责理解和表达，事实放在知识库里通过检索提供。这就是RAG（检索增强生成）存在的原因。

## 为什么会幻觉

从“预测下一个词”的本质可以直接推出幻觉的根源：模型的目标是**生成连贯的内容**，不是**保证内容真实**。当它不知道答案时，它不会说“我不知道”——训练数据里“我不知道”出现的概率往往低于“编一个合理的答案”。

具体原因包括：知识过时、问题信息不足、要求过细（逼它编）、材料冲突、采样随机性等。幻觉不是bug，是统计系统的固有行为特征。可以压低（限定资料、要求引用、允许说不知道），但不能根除。详见本库的《AI幻觉》深度文章。

## 为什么模型看起来会推理

需要分清两种“推理”：

- **模式匹配式推理**：题目与训练数据中的同类问题相似，模型按见过的套路输出正确过程。大部分日常“推理”属于这一类。
- **真正的逻辑保证**：模型没有逻辑引擎，不会因为“结论必须从前提推出”而自我约束。换一个它没见过的题型，或加入一个误导性前提，它可能同样流畅地推出错误结论。

判断方法很简单：把题目改成**需要多步组合、数据分布不同**的变体，如果正确率骤降，说明之前的“推理”大概率是模式匹配。

## 模型真正擅长和不擅长什么

**擅长：**

- 语言理解和生成，包括中文；
- 有明确模板的任务：摘要、分类、改写、翻译、提取；
- 代码补全与常见bug修复；
- 头脑风暴和初稿生成；
- 在给定资料范围内做结构化整理。

**不擅长：**

- 需要精确计算或逻辑链很长且不允许一步出错的任务；
- 需要实时或专有数据的任务（必须接检索或工具）；
- 需要“知道自己不知道”的任务；
- 需要稳定复现同一答案的任务（低temperature可以压低波动，但无法消除）；
- 高频调用且预算敏感的任务（需要权衡成本与收益）。

