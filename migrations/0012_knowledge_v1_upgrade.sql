## 为什么AI产品应该结构化输出

四个理由，按重要性排序：

1. **可验证**：JSON可以用schema校验，字段缺失、类型错误、枚举越界都能被程序发现；
2. **可组合**：输出直接进数据库、进下游流程、进报表，不需要二次解析和猜测；
3. **可度量**：结构化输出让质量指标（字段完整率、解析失败率）可统计，这是优化的前提；
4. **可回退**：解析失败时可以重试、降级、转人工，而自由文本失败时你甚至不知道它失败了。

