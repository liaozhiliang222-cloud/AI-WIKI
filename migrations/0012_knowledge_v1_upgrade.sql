## AI在证据链中的角色

| 环节 | AI可以做的 | 必须人做的 |
| --- | --- | --- |
| 原话 → 编码 | 提出候选编码 | 判断编码是否忠于原话 |
| 编码 → 主题 | 提供分组方案 | 判断主题对研究问题的解释力 |
| 主题 → Finding | 生成陈述草稿 | 确认Finding可验证、无解释 |
| Finding → Insight | 提出多个候选解释 | **选择机制解释、排除其他解释** |
| Insight → Implication | 帮助推演后果 | 判断业务含义的边界 |
| Implication → Recommendation | 起草建议 | 判断可行性、优先级、边界 |

**特别注意**：Finding→Insight是AI最危险的一环。AI很擅长生成“听起来深刻”的解释，但它不会验证解释。一个简单的防呆方法：**要求每个候选Insight必须挂接至少两条独立证据，并且列出可能的反例**——挂不上证据或想不出反例的解释，直接删除。

