## 三个业务场景的决策演示

### 场景一：内部知识库助手，数据敏感（选开源）

一家律所的合同分析助手，处理客户合同，数据不能离开内网。

- 隐私维度直接锁死公有API；
- 团队有运维能力（已有内部K8s）；
- 用量中等（每天几千次调用），GPU成本可控。

**决策**：本地部署开源模型。虽然付出了部署和运维成本，但隐私合规是硬约束，没有其他选项。注意：即使如此，也要把“开源模型”当作产品组件看待——模型的安全评测、版本升级、故障预案都要纳入运维体系。

### 场景二：面向C端的问答产品，成本敏感（选闭源或托管）

一个免费增值的写作助手，日均调用10万次，用户对延迟敏感，团队只有3个人。

- 自建10万QPS的推理服务需要数台GPU服务器和专职运维，团队规模撑不住；
- 用量大，但闭源API按量计费，成本可精确预测并随收入增长；
- 数据是用户输入的普通文本，无特殊合规要求。

**决策**：闭源API（或托管推理服务）。关键动作是**选好缓存和降级策略**把成本压下来（见《AI API成本是怎么构成的》）。等用量稳定、商业模式验证后，再评估是否值得为省API费自建。

### 场景三：对延迟和成本极度敏感的批处理（混用）

一个每天处理200万条短文本分类的流水线。

- 自建推理：前期投入高，但边际成本极低，吞吐可控；
- 闭源API：单价低但200万条×2次调用（输入+输出）的总费用可观；
- 任务简单（分类），不需要最强模型。

**决策**：先用小模型+自建推理跑通，把预算从“按Token付费”变成“按GPU摊销”。如果团队没有运维能力，退而求其次用最便宜的托管模型。**注意：批处理场景里“贵模型做简单任务”是最大的浪费，先用任务难度匹配模型大小。**

