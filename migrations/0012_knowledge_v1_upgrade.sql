## JSON Schema设计示例

生产环境建议用Schema（而不是仅示例）约束输出。一个信息抽取任务的Schema：

```json
{
  "type": "object",
  "required": ["finding", "evidence", "confidence"],
  "properties": {
    "finding": {
      "type": "string",
      "description": "研究发现的陈述，不超过50字"
    },
    "evidence": {
      "type": "array",
      "items": { "type": "string" },
      "description": "支持该发现的原话或文档引用，必须来自输入材料"
    },
    "confidence": {
      "type": "string",
      "enum": ["high", "medium", "low"],
      "description": "对结论的把握程度"
    }
  }
}
```

设计Schema的四个原则：

- **required字段宁少勿多**：字段越多，模型漏填概率越大；
- **枚举代替自由文本**：能用enum的地方不用string，显著提升稳定性；
- **description写清楚取值标准**：模型依赖字段描述理解语义，描述越具体输出越准；
- **保持扁平**：嵌套层级不超过2层，深嵌套是解析错误的高发区。

## 六种失败模式与处理策略

### 1. Validation失败（校验失败）

Schema校验不通过：缺字段、类型错误、枚举值非法。

**处理**：重试1~2次，把校验错误信息回传给模型让它修正。重试上限之后进入兜底（见第5条）。

```text
你的输出未通过校验：字段 confidence 的值 "maybe" 不在枚举 [high, medium, low] 中。
请修正后重新输出完整JSON。
```

### 2. Retry策略

**要点**：有上限的重试才有意义。建议：校验失败重试≤2次，解析失败重试≤2次，总重试上限3次。每次重试都消耗Token，无上限重试会把成本推向失控（见《AI API成本是怎么构成的》）。

### 3. Missing field（缺字段）

模型漏掉了required字段。

**处理**：把缺失字段的默认值策略写进Prompt（“字段无法确定时输出null，不要省略字段”）。程序侧对null字段要有明确的消费逻辑——**缺字段的错误比错误值更难发现，因为前者没有报错。**

### 4. Enum越界

模型输出了schema之外的枚举值。

**处理**：校验时把非法值映射到最近的合法值（如“medium-high”→high），并在日志中记录映射次数——**频繁越界说明枚举设计不符合模型的语言习惯**，应该改枚举而不是改代码。

### 5. Parsing error（解析错误）

输出包含Markdown围栏、额外文字、截断、非法转义，导致`JSON.parse`失败。

**处理**：解析器做容错（剥离围栏、截取第一个`{`到最后一个`}`），同时统计解析失败率。**解析失败率是结构化输出最重要的健康指标**：超过3%必须处理（换模型、调Schema、加提示）。

### 6. Schema evolution（Schema演进）

上线后需求变化，Schema增加字段或改类型。

**处理**：

- 字段只加不减：新字段给默认值，旧字段保留，保证历史数据兼容；
- 版本化：在输出里加`schema_version`字段，下游按版本解析；
- 演进时对历史数据做迁移脚本，而不是让解析器兼容所有历史版本。

## 常见实现模式

```text
模式1：要求JSON + 解析器容错 + 校验 + 重试
模式2：Schema约束（厂商原生支持时优先）
模式3：JSON + 工具调用（Function Calling）让厂商保证格式
```

**优先级建议**：能用厂商原生的结构化输出/工具调用约束就用（格式保证最强）；不能用的场景用“Schema+重试”兜底。无论哪种，**校验和重试都要自己写**——格式保证不等于语义正确。

