## 十项成本来源

### 1. Input Token（输入）

每轮请求发送给模型的内容，包括系统Prompt、历史、资料、问题。**这是大多数应用的主要成本项**——因为它随每个请求重复发生。

公式：`输入成本 = 每千Token输入单价 × 输入Token数 ÷ 1000`

### 2. Output Token（输出）

模型生成的内容。单价通常高于输入（3~5倍）。长输出任务（总结、生成文章、Agent多步推理）里，输出可能反超输入成为主要成本。

### 3. Prompt缓存

同一段系统Prompt反复发送时，许多厂商提供缓存计费（大幅低于原价）。**这是最容易省的钱**：把稳定的指令和资料放到可缓存位置，让命中率提升。

### 4. Embedding

向量化文本用于检索（RAG的前置）。按字符/Token计费，单价低，但**量大**——几百万条知识库文档向量化一次，费用可观；好在是一次性或低频成本。

### 5. 图片/多模态输入

按图片数量和分辨率计费，通常折算成Token。一张高清图可能等于几千Token。**把图片压缩到实际需要的分辨率，是成本优化第一课。**

### 6. OCR

文档识别按页计费。批量扫描场景（合同、票据）里，OCR成本可能超过模型调用成本。

### 7. ASR（语音转文字）

按音频时长计费。会议纪要产品的主要成本来源是它，不是后面的摘要模型。

### 8. Tool Call

工具调用通常产生额外Token（函数定义、参数、结果回传）。Agent每多一次工具调用，就多一轮输入+输出。**工具调用的隐藏成本 = 每轮完整的输入输出费用 × 调用轮数。**

### 9. Retry（重试）

结构化输出解析失败、超时、限流触发的重试，会把成本乘上重试系数。解析失败率5%意味着成本至少+5%，还要加上用户等待的体验损失。

### 10. 长上下文与并发

长输入直接放大单次成本；并发则影响限流和是否需要多供应商。**成本估算时，先乘用量再乘单次成本，而不是反过来。**

## 通用成本计算框架

```
单次功能成本 =
  (系统Prompt Token × 输入单价 +
   资料 Token × 输入单价 +
   历史 Token × 输入单价 +
   问题 Token × 输入单价) ÷ 1000
  +
  (输出 Token × 输出单价) ÷ 1000
  +
  附加成本（图片/OCR/ASR/Embedding）
  +
  重试系数 × 上述合计

月度成本 = 单次功能成本 × 日均调用量 × 30
```

两个容易漏的项：

- **历史累积**：多轮对话每轮都重发全部历史，成本随轮数线性增长。30轮对话的单次成本可能是一轮对话的10倍以上。
- **峰值系数**：真实用量有波动，估算时乘1.2~1.5的峰值余量。

## 三个示例计算

> 以下单价是示意值，用于演示公式，实际以你拿到的报价为准。

### 示例一：知识库问答（RAG）

- 系统Prompt：500 Token；检索片段：1500 Token；问题：200 Token；输出：800 Token
- 假设输入单价￥0.01/千Token，输出单价￥0.03/千Token（示意）

```
单次 = (2200 × 0.01 + 800 × 0.03) ÷ 1000 = 0.022 + 0.024 = ￥0.046
月成本（日均10万次）= 0.046 × 100000 × 30 = ￥138,000
```

**优化动作**：Prompt缓存命中系统Prompt和常用资料，单次可降到￥0.02以下；检索片段从1500降到800 Token，再省一半。**同样的功能，优化前后月成本可以差4倍。**

### 示例二：会议纪要（ASR + 摘要）

- 1小时会议：ASR约￥1（示意）；转写稿约1万Token，分段摘要输入2万Token、输出3000 Token

```
单次 = 1（ASR）+ (20000 × 0.01 + 3000 × 0.03) ÷ 1000 = 1 + 0.2 + 0.09 ≈ ￥1.29
月成本（日均500场）= ￥19,350
```

**观察**：ASR占了大头。优化方向不是换摘要模型，而是找更便宜的ASR服务、只转写需要的片段。

### 示例三：Agent（多轮工具调用）

- 单任务平均5轮，每轮输入2500 Token、输出1200 Token

```
单任务 = 5 × (2500 × 0.01 + 1200 × 0.03) ÷ 1000 = 5 × 0.061 = ￥0.305
月成本（日均2万任务）= ￥183,000
```

**观察**：Agent成本里，每一轮都是全量输入输出。限制轮数上限、压缩中间结果、用便宜的模型做中间步骤，是三种立竿见影的优化。**一个“会控制轮数”的Agent设计，比任何模型折扣都省得多。**

