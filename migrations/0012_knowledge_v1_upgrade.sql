## 普通方案为什么不行

先看直接总结的失败模式：

| 失败模式 | 原因 | 后果 |
| --- | --- | --- |
| 关键数字遗漏 | 中间遗忘：信息在长文中间被忽略 | 总结与原文不一致 |
| 无来源可查 | 模型没绑定原文位置 | 无法验证，无法审计 |
| 局部正确全局错 | 只看开头就下结论 | 总结与原文矛盾 |
| 长度失控 | 一次输出太长的内容质量崩坏 | 需要二次压缩，损失信息 |
| 重复与冲突 | 原文矛盾处模型按“出现次数多”取信 | 错误结论被固化 |

**核心问题**：直接总结把“读文档”和“写总结”压进一次调用，而这两件事的复杂度都应该被拆开。

## 七步工作流

```text
Document（原文）
  → 1 Parsing（解析与清洗）
  → 2 Chunking（分段）
  → 3 Section Summary（分节摘要）
  → 4 Evidence Extraction（证据提取）
  → 5 Cross-section Synthesis（跨节综合）
  → 6 Final Summary（最终总结）
  → 7 Human Review（人工复核）
```

### 第1步：Parsing（解析与清洗）

把PDF、扫描件、网页转成干净的纯文本：保留标题层级、表格、页码；去掉页眉页脚、导航噪声、乱码。

**验收标准**：清洗后的文本可以按标题找到每一节；表格没有丢失行列。

### 第2步：Chunking（分段）

按**文档结构**切分，而不是按固定字数硬切：

- 优先按标题层级（章节、小节）切分；
- 超长小节再按段落切分，并保留上下文衔接句；
- 每个分块标注：文档名、章节路径、页码。

**验收标准**：任何一段原文都能定位到唯一分块；没有分块横跨两个无关主题。

### 第3步：Section Summary（分节摘要）

对每个分块独立生成摘要。分块小，模型质量高，且错误被限制在单块内。

**Prompt模板**：

```text
你是文档分析助手。以下是从《{文档名}》{章节}提取的文本片段。
任务：生成这段内容的摘要。
要求：
1. 只依据本片段，不补充片段外的知识；
2. 保留所有具体数字、日期、名称；
3. 标注本段涉及的3个以内的关键主题词；
4. 输出JSON：
{
  "section": "章节路径",
  "summary": "不超过150字",
  "key_points": ["要点1", "要点2"],
  "numbers": [{"value": "数字原文", "context": "该数字的上下文"}]
}
