## 三个决策场景

### 场景一：企业知识库问答（选RAG）

一个中型企业有3000份制度文档，每周更新几十次，员工问“报销流程”“请假规则”“安全规范”。

- 材料规模：持续增长，永远超出任何窗口；
- 更新频率：以周为单位，必须实时生效；
- 对答案的要求：必须能回溯到具体条款。

**结论**：RAG是唯一可行方案。长上下文在这里连“能用”都算不上——3000份文档根本装不进窗口，而每次手动选择“相关文档”就等于人工检索。

### 场景二：单份复杂文档的深度理解（选长上下文）

分析师拿到一份120页的招股书，问题包括“第3章的收入确认政策与第8章财务数据是否一致”。

- 材料规模：单份文档，可能刚好在窗口范围内；
- 需求本质：跨章节综合比对，检索会切碎关系；
- 使用频率：低频、高价值，成本不是首要约束。

**结论**：把文档整体放进长上下文，配合“先通读再提问”的方式。RAG反而会因切分破坏章节间的引用关系。

### 场景三：混合方案（大多数真实产品）

一个客服系统：知识库有5万条问答，同时用户会发送“这一单的物流异常+历史订单信息”。

- 固定的制度性知识：走RAG检索；
- 用户私有数据（订单、物流状态）：走程序化查询（结构化数据，根本不该让模型“记住”）；
- 两者都拿到后，一起放进上下文让模型组织回答。

**结论**：检索负责“找到知识”，长上下文负责“容纳少量但关键的临时材料”，代码负责“精确数据”。三者的分工不是技术时髦，而是各自对应信息的不同特性：知识库需要可更新、可追溯；临时材料需要一次性的全局视角；结构化数据需要零误差。

## 常见的两个失败模式

**RAG失败**：检索不到关键证据。症状是模型回答“没有找到相关信息”或基于残缺材料硬答。原因通常不是模型，而是切分破坏了语义（条款被拦腰切断）、检索词与文档用词不一致、没有重排序。排查顺序：先人工验证“这条知识是否在库里”，再检查“为什么没被检索到”。

**长上下文失败**：关键信息被淹没。症状是材料里明明有答案，模型却答错。原因是中间遗忘、材料重复、无关内容稀释注意力。排查顺序：把关键信息移到开头或结尾再测；如果位置移动后答案变化，说明是窗口利用问题而非模型能力问题。

> 测试技巧：用同一问题分别测试“全量材料”“只给开头”“只给中间”“只给结尾”四种输入，可以快速定位是“材料没有进入窗口”还是“进了窗口但没被利用”。

## 一个完整的混合示例

**任务**：内部法律顾问助手，回答“某供应商合同中的违约条款适用哪些责任”。

处理链：先检索合同库找到该合同 → 全文进入上下文（合同通常几万字，窗口可容纳）→ 同时检索“违约责任”相关条款 → 模型基于全文+条款回答，并标注引用位置。

这套链路同时用到了检索（找合同、找条款）、长上下文（全文保留、避免切碎）和引用校验（回答绑定原文位置）。**成熟的系统不会在“RAG还是长上下文”之间站队，而是按信息类型分配方案。**

