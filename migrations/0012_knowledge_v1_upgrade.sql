## 七种幻觉的拆解

### 1. 模型知识幻觉

模型训练数据里的知识有截止时间、有冷门盲区，被问到时它会用“看起来合理的编造”补位。

**触发条件**：问题涉及训练截止之后的新闻、冷门事实、具体数字。

**例子**：

> 问：2026年发布的中端国产模型里，哪一款中文长文本能力最好？
> 答：X模型（虚构）在中文长文本评测中排名第一……（该模型根本不存在，或结论早已过时）

**拦截手段**：时效性内容强制走检索；Prompt中明确“只回答资料范围内的内容，资料没有就说不知道”。

### 2. 检索幻觉

RAG系统检索到的片段本身不相关或残缺，模型却基于错误材料作答。

**触发条件**：检索质量差（切分不合理、召回不足）、资料库里根本没有答案但用户以为有。

**例子**：问客服“会员如何退订”，检索到的片段是“会员权益说明”里关于续费的部分，模型顺着它编了一套退订流程。

**拦截手段**：提升检索（混合检索+重排序，见《混合检索与重排序》）；对“检索分数过低”的情况直接进入兜底回答；要求模型区分“材料明确说了”和“材料没提”。

### 3. 引用幻觉

模型给出了具体来源——论文、网页、页码、数据出处——但这些来源**不存在或内容不符**。

**触发条件**：用户要求“给出处”，模型训练见过大量“引文+出处”的格式，于是补全格式。

**例子**：

> 答：根据2024年某研究报告（PDF第47页），70%的企业……（该报告存在，但第47页讲的是别的；或该报告根本不存在）

**拦截手段**：引用必须来自**实际提供给模型的材料**，不能来自“模型记忆”；系统层做链接校验（引用的URL是否真的出现在材料里）；高危场景禁用模型编造的引用，只允许“材料片段编号引用”。

### 4. 推理错误

不是编造事实，而是推理链条里某一步出错，导致结论错误。模型没有逻辑引擎，多步推理每一步都有出错概率，错误会累积。

**触发条件**：多条件判断、数值计算、长链条逻辑。

**例子**：库存系统判断“订单量+在途量是否超过安全库存”，模型算对了前两步，第三步把在途量当成已入库量，得出“可以接单”的错误结论。

**拦截手段**：数值与规则计算**不交给模型**，交给代码；模型只做“把自然语言转成结构化参数”这一步，再让程序校验。

### 5. 信息不足型幻觉

不是模型故意编造，而是问题本身缺少必要信息，模型被逼着补全假设。

**触发条件**：模糊问题、缺少上下文、开放式的“帮我分析一下”。

**例子**：问“帮我把这个方案写得更有说服力”，没说给谁看、什么场景、什么立场，模型只能编一个通用答案，其中必然包含与实际情况不符的假设。

**拦截手段**：Prompt里要求“信息不足时先提问，最多问3个关键问题再作答”；产品层把必要参数做成表单，而不是开放输入。

### 6. Prompt诱导型幻觉

提示词本身在诱导模型输出不存在的内容，常见于“角色扮演+指定结论”。

**触发条件**：系统Prompt包含“你要表现得好像真的经历过”、要求“以专家身份给出确定结论”、或先入为主地预设结论让模型论证。

**例子**：

> 系统提示：你是一位有20年经验的食品安全专家，请确认我司产品的检测流程完全合规。（模型会配合输出肯定的结论，即使它并不知道检测报告内容）

**拦截手段**：区分“表达风格”与“事实主张”；对事实性问题禁用角色扮演式的身份虚构；要求“以提供的材料为准”。

### 7. 过期知识型幻觉

知识本身在训练时是真实的，但现在已经过时。这是最阴险的一种——因为**来源是真的，只是旧了**。

**触发条件**：政策、价格、API用法、产品功能这类高频变化的信息。

**例子**：让模型写某云厂商对象存储的价格对比，它引用的是两年前的价格表——数字全是真实的，但全都不对。

**拦截手段**：变化型知识一律检索最新来源；把“信息更新时间”纳入回答展示；高危场景要求标注“信息来源日期”。

