## 五级降级设计

按“AI完全正常”到“AI完全不可用”分级，每一级定义触发条件、行为和出口：

```text
Level 0  正常：模型正常，直接返回结果
Level 1  重试：临时故障，有限次重试（指数退避）
Level 2  备用模型：主模型不可用时切换备用模型
Level 3  规则系统：无模型可用时，用规则/模板/缓存顶住
Level 4  人工处理：全部失效，进入人工队列
```

### Level 0：正常

无额外动作。但要**记录基线指标**（成功率、延迟、Token用量），没有基线就无法判断降级是否生效。

### Level 1：重试

**适用**：超时、5xx、限流（可等待类故障）。

**设计要点**：

- 重试上限：2~3次，超过立即降级，不要无限重试；
- 退避策略：指数退避+抖动（如1s、2s、4s），避免重试风暴；
- 幂等性：重试的请求必须幂等（尤其是生成类任务，防止重复扣费和重复入库）；
- 记录重试原因和次数——重试率高是上游故障的早期信号。

### Level 2：备用模型

**适用**：主模型长时间不可用、限流持续。

**设计要点**：

- 备用模型的选择标准：**能力够用、渠道独立**。主模型和备用模型不要来自同一个可能同时故障的渠道；
- 备用模型可能是便宜的小模型——输出质量略降但功能可用；
- 切换要自动化：连续N次重试失败后自动切换，而不是等人工操作；
- 备用模型的表现要单独监控——它可能在悄悄变差。

### Level 3：规则系统

**适用**：所有模型都不可用，但业务不能停。

**设计要点**：

- 提前把高频问题的答案做成规则/模板（如FAQ兜底、固定格式模板）；
- 检索类功能降级为关键词搜索；
- 生成类功能降级为固定模板+变量填充；
- 降级输出必须**明确标注**“当前为简化版本”，避免用户误以为这是AI的完整能力。

**案例**：某客服系统的主模型故障期间，兜底规则库覆盖了Top 50高频问题（约70%的流量），其余请求进入人工队列。用户看到的是“答案变简短了”，而不是“系统坏了”。

### Level 4：人工处理

**适用**：以上全部失效，或任务本身不可降级（高价值、不可逆操作）。

**设计要点**：

- 自动进入人工队列，并附上上下文（原始请求、已尝试的降级路径）；
- 对用户透明：告知“正在转人工处理”；
- 人工队列要有SLA和监控，不能变成“黑洞”。

