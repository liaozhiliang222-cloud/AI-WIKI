{chunk}
```

**验收标准**：抽查10%分块，摘要中的数字与原文一致率100%。

### 第4步：Evidence Extraction（证据提取）

这一步容易被跳过，但它是整条链路的保险：**提取原文中可引用的关键陈述**，让最终总结的每个结论都有出处。

```json
{
