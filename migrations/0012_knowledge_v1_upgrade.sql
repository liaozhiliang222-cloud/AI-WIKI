## Step 1：模型的信息是否足够？

**症状**：回答含糊、套话、编造细节。

**检查**：模型需要的所有事实是否都在输入里？信息不足是幻觉的第一来源——模型不会说“我不知道”，它会编一个合理的答案。

**修复**：

- 把必要的事实、资料、背景直接放入Prompt；
- 在Prompt中明确：“只基于提供的资料回答，资料中没有的，明确说不知道”；
- 产品层面，把关键参数做成表单字段，而不是让用户自由输入。

> 案例：客服助手答错退换货规则。排查发现知识库没接进去——模型在凭训练记忆回答两年前的规则。接上检索后同一问题回答正确。

## Step 2：任务目标是否清楚？

**症状**：输出方向对但内容“不是我要的”。

**检查**：Prompt里是否只有“帮我分析一下”这类模糊指令？模型不知道你的输出要面向谁、达到什么目的、什么算好。

**修复**：用“角色+目标+输入+规则+输出+校验”结构重写：

```text
你是【角色】。
目标：【用一句话说明你要达成什么】。
输入：【说明模型会收到什么】。
规则：【列出必须遵守的约束，逐条编号】。
输出：【说明输出格式，必要时给出模板】。
校验：【说明如何判断输出合格】。
```

## Step 3：规则是否冲突？

**症状**：模型时而遵守A规则，时而违反，行为不稳定。

**检查**：Prompt里的多条规则是否有矛盾？例如“回答要简洁”和“请详细说明每个步骤”同时出现；或“用中文回答”和示例是英文。

**修复**：

- 规则逐条编号，删除互相矛盾的条目；
- 用示例（而不是形容词）表达模糊要求——“简洁”不如给出一个理想的回答示例；
- 测试时只改一条规则，观察行为变化，避免多条规则互相干扰。

## Step 4：是否需要Few-shot示例？

**症状**：规则都清楚，但输出格式不稳定、边界情况判断错误。

**检查**：任务是分类、格式化、风格模仿类吗？这类任务里，**一个高质量示例胜过三句规则描述**。

**修复**：加入2~3个覆盖典型+边界情况的示例：

```text
示例1：
输入：...
输出：...

示例2（边界情况）：
输入：...
输出：...
```

注意：示例要覆盖**容易混淆的边界**，而不是堆相似例子。5个相似的正面示例，不如“2个正面+1个反面”有用。

## Step 5：是否需要结构化输出？

**症状**：输出是自然语言，下游程序无法可靠处理；或需要多次解析。

**检查**：这个输出会被程序消费吗？会被二次处理、入库、统计吗？是 → 要求结构化输出。

**修复**：在Prompt中给出JSON Schema或示例，并要求严格按格式输出：

```text
输出格式（严格JSON，不要额外解释）：
{
  "summary": "一句话总结",
  "category": "枚举值之一",
  "confidence": "high|medium|low"
}
```

结构化输出详见《为什么要让AI输出结构化JSON》。注意：**要求JSON后，解析失败率是新的度量指标**，要统计并跟踪。

## Step 6：是否应该拆成多个步骤？

**症状**：任务复杂时输出质量不稳定，时而好时而差；长输出后半段质量明显下降。

**检查**：任务是否包含多个子任务？（例如“阅读这份报告→找出问题→给出建议→写成邮件”）把多个子任务塞进一个Prompt，模型容易顾此失彼。

**修复**：拆成多步调用，每步一个Prompt、一个中间产物：

```text
第1步：提取关键事实（结构化输出）
第2步：基于事实生成建议
第3步：把建议整理成邮件格式
```

每一步的输出都是下一步的输入，中间产物可检查、可修正。**拆步是成本，但也是可控性的来源。**

## Step 7：问题是否属于模型能力限制？

**症状**：以上六步都做了，输出仍然不对。

**检查**：换更强的模型或换思路测试。如果任务在最强模型上仍然失败，大概率是能力边界问题（长逻辑链、精确计算、最新知识），而不是Prompt问题。

**修复**：

- 精确计算 → 交给代码，不让模型算；
- 最新知识 → 接检索或工具，不让模型记；
- 超长推理链 → 拆步骤（回到Step 6）或换推理模型；
- 如果必须用当前模型 → 降低期望，加人工复核节点。

**关键认知**：Step 7不是“最后没办法了才查”，而是**先快速验证**——花5分钟用一个强模型跑一遍，能立刻区分“Prompt问题”还是“能力问题”。

## 完整案例：从失败到修复

