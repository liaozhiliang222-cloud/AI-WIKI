| 10 | 稳定性 | 停机历史、限流强度、SLA | 厂商状态页+同行口碑 |
| 11 | 隐私 | 数据是否允许进入公有API？ | 合规部门结论 |
| 12 | 并发 | 峰值QPS与厂商限流关系 | 压测 |
| 13 | 工具调用 | 是否需要调用函数/工具？ | 工具调用场景实测 |
| 14 | 结构化输出 | 是否必须稳定输出JSON？ | 结构化输出实测 |

**关键认知**：这14个维度里，通常只有3~5个真正决定选型，其余只是“差不多就行”。比如一个内部文档提取工具，延迟和价格是决定性的，排行榜分数则完全无关。先把决定性维度找出来，选型范围立刻缩小到两三个候选。

## 第二步：模型评估打分表

对每个候选模型，按业务权重打分（1~5分）。权重是**你自己定的**，不是模型厂商定的：

| 维度 | 权重 | 模型A | 模型B | 模型C | 说明 |
| --- | --- | --- | --- | --- | --- |
| 任务复杂度匹配 | 30% | 4 | 5 | 3 | 权重最高的维度 |
| 中文质量 | 20% | 5 | 4 | 4 | 目标用户是中文 |
| 结构化输出 | 15% | 5 | 4 | 3 | 必须稳定JSON |
| 延迟 | 15% | 3 | 4 | 5 | 交互式场景 |
| 价格 | 10% | 4 | 3 | 5 | 中频调用 |
| 稳定性 | 10% | 3 | 4 | 4 | 生产依赖 |
| 加权总分 | 100% | 4.10 | 4.25 | 3.85 | 待业务评测验证 |

打分不是最终答案，它的作用是**把主观印象变成可讨论的表格**。如果两个模型得分接近（差距小于0.3），不要再纠结分数，直接进入第三步用真实业务数据裁决。

## 第三步：怎么测（比选谁更重要）

用生产环境里真实的20~50个案例，构造一个小型评测集，包含：

- 典型输入（80%）：业务里最常见的场景；
- 边界输入（15%）：长文本、奇怪格式、模糊问题；
- 对抗输入（5%）：含误导信息、信息不足、需要拒绝回答的情况。

对每个案例预先写好**参考答案和评分标准**（正确/部分正确/错误/拒答），然后逐一对比候选模型。重点测三类能力：

1. **结构化输出稳定性**：连跑20次，统计JSON解析失败率。失败率超过5%的模型直接出局——这意味着每20次调用就有1次需要重试。
2. **关键信息保真**：答案中的数字、名称、条款是否与材料一致。这是幻觉的量化指标。
3. **边界行为**：信息不足时是否诚实拒答，还是硬编。

**评测集要落在代码里**：写成JSON文件+评测脚本，以后换模型、换版本、调Prompt都跑同一套。没有评测集的选型讨论，本质上是在交换个人感受。

