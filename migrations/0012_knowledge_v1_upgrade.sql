## 输入：原始材料（虚构）

假设你为一家连锁咖啡品牌做用户研究，以下是三段虚构访谈原话：

```text
P07：我家楼下那家店，早上高峰排队要十几分钟，我赶时间就不买了。
P08：用App下单其实挺方便的，但我要走到店里才能看到还有没有位置，有时候到了没位子。
P09：会员积分有什么用啊，兑换的东西我都用不上，不如直接打折。
```

## 第1~2环：原话 → 开放编码

| 原话 | 开放编码 |
| --- | --- |
| “排队要十几分钟，我赶时间就不买了” | 高峰等待导致购买放弃 |
| “我要走到店里才能看到还有没有位置” | 座位信息不可预知 |
| “积分兑换的东西用不上，不如直接打折” | 积分价值感知低 |

## 第3环：主题

三个编码共同指向一个主题：**购买决策中的不确定性与时间成本**。注意：这里已经做了第一层抽象——把“排队”“找座位”“积分不值”归纳为“不确定性与时间成本”，但归纳是否成立，要回到原话验证（排队是时间成本，找座位是不确定性，积分不值其实属于激励设计——它与其他两条的机制不同，归入本主题时需要标注为弱关联）。

**这一步是证据链最容易断掉的地方**：主题越抽象，越要确认每一层的归纳依据。

## 第4环：Finding（发现）

**Finding是“数据里有什么”的陈述**——忠实、可验证、不解释。

> Finding A：3位受访者中，2位提到高峰时段等待导致放弃购买（P07、P08间接相关）。

Finding的特征：直接来自编码，换一个人复核数据会得出同样的陈述，没有因果解释。

## 第5环：Insight（洞察）

**Insight是“数据为什么是这样”的机制性解释**——它是Finding之上的推理，必须有依据、可以被挑战。

**坏洞察（不是洞察）**：

> “消费者认为价格贵，所以要提高性价比。”

问题：数据里根本没有价格相关编码，这是模型式的泛化套话；没有机制，没有证据链。

**另一个坏例子**：

> “消费者很忙，所以品牌要提升便利性。”

问题：这是常识，不是从数据推出的机制；“忙”是推断，原话里没有。

**好洞察（示例）**：

> 消费者的购买放弃不是发生在价格比较环节，而是发生在**信息不对称环节**——他们无法在决策前获知“要等多久”“有没有座位”。咖啡本身的吸引力（P07愿意来、P08愿意用App）没有失效，失效的是决策前信息的可获取性。因此“便利”不是营销口号，而是**决策信息的基础设施**。

为什么这个算洞察：

- 有机制：“信息不对称→决策前信息缺失→放弃购买”因果链清晰；
- 有依据：每步都能挂到原话（P07排队、P08找座位）；
- 有区分度：它区别于“消费者忙所以要便利”这类常识，指出了具体的失效环节；
- 可挑战：如果引入反例（有人愿意排队等新品），链条就需要修正。

## 第6~7环：Implication（含义）与Recommendation（建议）

**含义**：洞察对业务意味着什么。

> 如果失效环节是决策前信息，那么解决方案应该发生在**决策前**，而不是购买时或购买后。折扣、会员积分（P09）解决的是另一个问题（价值感知），它们无法修复信息缺失导致的放弃。

**建议**：可执行、可验证的动作。

> 建议1：在App和门店入口提供实时排队与座位状态（直接修复信息缺失）；
> 建议2：为“信息修复类功能”建立独立指标——如“到店前查询率”“查询后到店率”，而不是只看整体销量（让建议可验证）；
> 建议3：P09的积分问题单独立项，不要与本次洞察混为一谈（明确边界）。

**建议与洞察的对应关系必须清楚**：每个建议都要能回答“它解决的是洞察链条中的哪一环”。

