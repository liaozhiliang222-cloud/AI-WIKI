## Token如何占用上下文

窗口以Token（文本切分单元）计量。不同类型的输入占用方式不同：

| 占用项 | 说明 | 常见陷阱 |
| --- | --- | --- |
| 系统Prompt | 每次请求都会发送，长期占位 | 越写越长，不知不觉吃掉几千Token |
| 聊天历史 | 多轮对话全部累计 | 20轮对话后，早期信息还在占用 |
| 资料/文档 | 你贴入的参考内容 | 全文粘贴往往远超真正需要 |
| 模型输出 | 生成的内容也会占窗口 | 长输出会挤占后续输入的容量 |

一个容易忽略的点：**模型输出也占窗口**。如果窗口是128K，你塞了120K输入，模型最多只能再输出8K——长文档任务经常在这里静默失败：不是模型“不会写”，是它“写不下”。

> 判断一段文本占多少Token，不要凭感觉。中文大约1个字≈1~2个Token，英文约4个字符≈1个Token，但代码和特殊符号差异很大。用厂商的Token计数工具实测（例如OpenAI Tokenizer），或直接用API返回的usage字段。

## 长上下文不等于长记忆

这是最普遍的误解。窗口长只表示模型**能读到的材料多**，不表示模型**能记住的材料多**，更不表示跨会话记忆（那是另一套系统）。

三个已经被反复验证的现象：

1. **中间遗忘（Lost in the Middle）**：把关键信息放在长文档的开头和结尾，模型更容易利用；放在中间，最容易丢失。论文实验显示，即使窗口足够容纳全部材料，中间位置的信息被正确使用的比例仍会显著下降。
2. **注意力稀释**：材料越长，模型对每部分信息的“关注预算”越薄。100条候选里有一条关键证据，它不一定“看见”那一条。
3. **重复与冲突放大**：材料里如果有互相矛盾的说法，长上下文中模型更可能采用“出现更多次”或“更靠后”的说法，而不是“更正确”的说法。

**实用推论**：关键信息要么放开头，要么放结尾；中间位置留给辅助材料；重要结论要求模型引用原文片段来核对。

## 信息密度：比窗口大小更重要的指标

两个配置对比：

- 配置A：窗口128K，塞入120K的冗余材料（合同扫描件、重复条款、无关章节）；
- 配置B：窗口32K，经过清洗与检索后只放8K的高相关片段。

大部分任务里，**配置B的效果更好且成本只有A的零头**。原因是模型的质量取决于“相关信息是否在窗口内且足够突出”，而不是“窗口内信息总量有多大”。

信息密度可以量化：进入窗口的资料中，与当前任务直接相关的比例。设计Prompt和工作流时，把提高信息密度当作第一目标：删重复、删无关、把长文档切成相关片段、把关键结论前置。

## 长上下文还要算成本账

长上下文不是免费的。同一模型，输入Token越多：

- **成本越高**：输入按Token计费，128K全量输入的成本通常是精简后输入的十几倍；
- **延迟越高**：模型需要“读完”全部输入才开始输出，长输入的首字延迟明显增加；
- **并发变差**：长请求占用更多算力，同样的吞吐下能支撑的并发更少。

对高频业务场景，先把“每次请求平均输入多少Token”这个数字算出来，再决定要不要用长上下文，是控制成本的第一步。

## 实际案例：一份100页PDF

假设你要分析一份100页的上市招股书（约20万字，按中文估算约20万Token以上）：

| 方案 | 做法 | 结果 |
| --- | --- | --- |
| 直接塞入 | 全文放进128K窗口 | 放不下或溢出；即便放得下，中间章节的关键数字容易被遗漏；单次成本高 |
| 分章摘要 | 每章单独摘要（每章约1~2万Token），再汇总 | 每步可控、可回溯；但跨章节的数字勾稽关系（如“第3章收入”与“第5章成本”对不上）容易漏 |
| 分章摘要+关键证据表 | 摘要之外，用结构化输出提取“数字+所在章节+原文引用”，再对证据表做交叉核对 | 最慢但最可靠：既能回答全局问题，也能回答“这个数字在哪一章” |

**结论**：窗口是给“已经选好的材料”用的，不是给“所有材料”用的。选择工作流时，先问：我需要的答案，是“在一个章节内能找到”，还是“要跨章节综合”？前者用检索+局部阅读，后者才值得动用长上下文。

