## 一个完整的失败例子

**任务**：一个知识库产品需要回答“我司报销政策中，住宿费上限是多少”。

- **第一版**：直接把整本员工手册塞进上下文让模型回答。结果：模型说“单日上限800元”——手册里写的是“一线城市800元，其他城市500元”，中间章节的细则被“中间遗忘”吞掉了。
