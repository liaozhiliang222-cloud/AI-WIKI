**研究者的工作**：不是照单全收，而是逐条核对——编码是否忠于原话？是否漏掉重要含义？是否引入模型自己的推断？例如“工具易用性主观差异”这个编码就是AI的推断（P05没说“主观”，说的是两件事），研究者应改为更贴原话的“新旧用户上手差异”或直接删除。

## 第2步：编码合并（Code Merge）

开放编码往往过碎（上面10个编码），需要合并为更上层的类别。

**Prompt模板**：

```text
以下是访谈编码清单。请按语义相近原则合并编码：
1. 合并后每个类别列出包含的原编码和支撑原话数量；
2. 标注哪些合并是确定的（high），哪些有歧义（medium）；
3. 输出JSON。
输出格式：
{
  "merged": [
    {
      "category": "合并后的类别名",
      "includes": ["原编码1", "原编码2"],
      "quote_count": 3,
      "confidence": "high|medium"
    }
  ]
}
```

**AI输出**：

```json
{
  "merged": [
    {"category": "旧习惯阻力", "includes": ["习惯性使用旧工具", "跟随领导行为"], "quote_count": 2, "confidence": "high"},
    {"category": "工具生态碎片化", "includes": ["工具数量过多", "多工具切换负担"], "quote_count": 2, "confidence": "high"},
    {"category": "领导示范缺失", "includes": ["领导不带头使用"], "quote_count": 1, "confidence": "high"},
    {"category": "表面遵从", "includes": ["表面遵从实际抵制"], "quote_count": 1, "confidence": "high"},
    {"category": "通知与打扰", "includes": ["新工具消息不及时查看", "通知打扰"], "quote_count": 2, "confidence": "high"},
    {"category": "培训与上手", "includes": ["培训效果差", "工具易用性主观差异"], "quote_count": 2, "confidence": "medium"}
  ]
}
```

**研究者的工作**：“旧习惯阻力”把“习惯用邮件”和“跟随领导”合并是否合理？两者机制不同——一个是个人习惯，一个是组织层级影响。建议拆开。合并标准要由研究问题决定，AI只提供候选。

## 第3步：主题归纳（Theme）

合并后的类别进一步归纳为主题。

**AI输出**：

```text
主题1：组织行为惯性
  包含：旧习惯阻力、领导示范缺失、跟随领导行为
主题2：工具生态与认知负担
  包含：工具生态碎片化、通知与打扰
主题3：推行方式与接受度
  包含：表面遵从、培训与上手
```

**研究者的工作**：主题必须**由研究问题校准**——如果研究问题是“什么因素决定远程工具采纳”，主题1和3都重要；如果研究问题是“工具设计如何影响体验”，主题2才是核心。主题不是“数据里最明显的分组”，而是“对研究问题最有解释力的分组”。

## 第4步：反例检查（Counterexample）

这是AI辅助研究里最容易被跳过的环节，也是最能区分“分析”与“复述”的环节。逐一挑战每个主题：

**Prompt模板**：

```text
针对以下主题和支撑编码，找出不支持该主题的原话（反例），或指出主题下编码之间的矛盾。
如果每个主题下都有反例或矛盾，请如实报告，不要强行统一。
```

**示例检查结果**：

- 主题1（组织行为惯性）反例：P05说“我妈一下就学会了”——说明个人层面学习不是普遍障碍，主题1的“阻力”叙事在P05身上不成立；
- 主题3（推行方式与接受度）矛盾：P04“表面遵从”说明强制推行引发抵制，但P03“领导带头我就用”说明领导示范可以促进接受——两者指向不同机制，不应合并表述。

**研究者判断**：P05是女儿教母亲使用，与职场场景不同，可视为边界案例单独标注，不推翻主题1，但要在报告里说明；P03与P04的矛盾则是真实的张力，值得展开。

## 第5步：洞察形成（Insight）

基于以上过程，形成有证据支撑的洞察：

```text
洞察（示例）：
在本次虚构访谈中，“领导示范”和“强制推行”对工具采纳的作用方向相反：
领导示范通过模仿机制促进采纳（P03），强制推行则诱发表面遵从（P04）。
这说明采纳障碍的根源可能不是工具本身，而是组织内的行为信号冲突——
当领导行为（发邮件）与新制度（用新软件）不一致时，员工跟随的是领导行为。
```

**为什么这是洞察而不是复述**：它没有停留在“员工不喜欢换工具”，而是把三个编码（领导不带头、跟随领导、表面遵从）组织成**有机制的因果解释**，并且可以被反例检查所挑战。

## 适合AI做与必须人工判断的边界

| 环节 | AI的角色 | 为什么必须人工 |
| --- | --- | --- |
| 逐条编码 | 提出候选编码 | 编码忠于原话的语义判断 |
| 编码合并 | 提供合并候选 | 合并标准由研究问题决定 |
| 主题归纳 | 提供分组方案 | 主题必须对研究问题有解释力 |
