    {
      "claim": "结论性陈述",
      "quote": "原文引用（逐字）",
      "section": "章节路径",
      "page": "页码（如有）"
    }
  ]
}
```

**验收标准**：每条quote能在原文中精确检索到；claim不超过quote语义范围。

### 第5步：Cross-section Synthesis（跨节综合）

把分节摘要和证据汇总，由模型寻找**跨章节的联系与矛盾**——这是单块阅读做不到的。

**Prompt模板**：

```text
你收到了一份文档的分节摘要和证据清单。
任务：
1. 找出跨章节一致的主题，说明它们的支撑证据；
2. 找出跨章节矛盾（数字对不上、说法冲突），列出双方原文位置；
3. 输出JSON：
{
  "themes": [{"theme": "主题", "evidence": ["证据编号"]}],
  "contradictions": [{"issue": "矛盾描述", "side_a": "位置", "side_b": "位置"}],
  "gaps": ["信息缺失的地方"]
}
```

**验收标准**：矛盾列表里的每一项都能在原文两个位置找到。

### 第6步：Final Summary（最终总结）

基于第5步结果生成最终总结，按目标读者调整详略。

**Prompt模板**：

```text
基于以下主题、矛盾和证据清单，为【目标读者】生成文档总结。
结构：背景 → 核心结论（每条附证据编号）→ 主要矛盾与风险 → 建议下一步。
要求：不引入证据清单之外的内容；总长不超过800字。
```

**验收标准**：总结中每个结论都能追溯到证据编号；无新增事实。

### 第7步：Human Review（人工复核）

机器链路到此为止。人工只复核高风险点，而不是通读全文：

- 矛盾清单是否属实；
- 关键数字是否与原文一致（抽样）；
- 总结中是否有证据清单外的“模型记忆”。

